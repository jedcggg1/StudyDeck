const TranslationContext = createContext<Translate>((key) => key);

export const LanguageProvider: React.FC<{ language: Language; children: React.ReactNode }> = ({
  language,
  children
}) => {
  const translate = useMemo<Translate>(
    () => (key, values) => {
      const translated = language === 'th' ? THAI_TRANSLATIONS[key] || key : key;
      return values
        ? Object.entries(values).reduce(
            (result, [name, value]) => result.split(`{${name}}`).join(String(value)),
            translated
          )
        : translated;
    },
    [language]
  );

  return <TranslationContext.Provider value={translate}>{children}</TranslationContext.Provider>;
};

export const useTranslation = (): { t: Translate } => ({
  t: useContext(TranslationContext)
});
